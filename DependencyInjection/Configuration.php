<?php

declare(strict_types=1);

namespace Pumukit\OpencastBundle\DependencyInjection;

use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

class Configuration implements ConfigurationInterface
{
    public const DEFAULT_NOTIFICATION_TEMPLATE = '<h2>Hello, {{username}}</h2><p>Your multimedia object named {{multimediaObject.title}} is already available in the platform. Check it at: <a href="{{url}}">{{url}}</a></p>';

    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('pumukit_opencast');
        $rootNode = $treeBuilder->getRootNode();

        $rootNode
            ->validate()
            ->ifTrue(static fn (array $config): bool => $config['enable'] && '' === trim((string) $config['host']))
            ->thenInvalid('pumukit_opencast needs host when it is enabled')
            ->end()
            ->children()
            ->booleanNode('enable')
            ->defaultTrue()
            ->info('If false, nothing connects to Opencast: the importer gives 404, the listeners do nothing, the commands fail and host is not required')
            ->end()
            ->scalarNode('host')
            ->defaultNull()
            ->info('Opencast server URL (presentation or all-in-one node)')
            ->end()
            ->scalarNode('admin_host')
            ->defaultNull()
            ->info('Opencast admin node URL. If null, it is asked to the server (/info/components.json)')
            ->end()
            ->scalarNode('username')
            ->defaultValue('')
            ->info('Digest user of the Opencast REST endpoints (org.opencastproject.security.digest.user). If empty, the requests are anonymous')
            ->end()
            ->scalarNode('password')
            ->defaultValue('')
            ->info('Digest password of the Opencast REST endpoints (org.opencastproject.security.digest.pass)')
            ->end()
            ->booleanNode('insecure')
            ->defaultFalse()
            ->info('Do not verify the TLS certificate of Opencast')
            ->end()
            ->scalarNode('player')
            ->defaultValue('/paella7/ui/watch.html')
            ->info('Opencast player URL or path')
            ->end()
            ->scalarNode('scheduler')
            ->defaultValue('/admin-ui/index.html#/events/events')
            ->info('Opencast admin URL or path of the recordings, relative to admin_host')
            ->end()
            ->booleanNode('show_importer_tab')
            ->defaultTrue()
            ->info('Show the Opencast importer in the back-office menu')
            ->end()
            ->booleanNode('batchimport_inverted')
            ->defaultFalse()
            ->info('Import the recordings with presenter and presentation switched by default')
            ->end()
            ->booleanNode('delete_archive_mediapackage')
            ->defaultFalse()
            ->info('Delete the Opencast event when the last multimedia object of its mediapackage is deleted')
            ->end()
            ->booleanNode('manage_opencast_users')
            ->defaultFalse()
            ->info('Create, update and delete the PuMuKIT users in Opencast')
            ->end()
            ->booleanNode('sync_series_with_opencast')
            ->defaultFalse()
            ->info('Create, update and delete the PuMuKIT series in Opencast')
            ->end()
            ->booleanNode('error_if_file_not_exist')
            ->defaultTrue()
            ->info('Fail the import if a track file is not accessible with url_mapping')
            ->end()
            ->arrayNode('url_mapping')
            ->info('Opencast URLs and the local paths where the same files are mounted')
            ->arrayPrototype()
            ->children()
            ->scalarNode('url')->isRequired()->end()
            ->scalarNode('path')->isRequired()->end()
            ->end()
            ->end()
            ->end()
            ->arrayNode('sbs')
            ->info('Side by side video')
            ->addDefaultsIfNotSet()
            ->children()
            ->booleanNode('generate_sbs')
            ->defaultFalse()
            ->info('Generate the side by side video when a mediapackage is imported')
            ->end()
            ->scalarNode('profile')
            ->defaultValue('sbs')
            ->info('Encoder profile of the side by side video')
            ->end()
            ->booleanNode('use_flavour')
            ->defaultTrue()
            ->info('Use the Opencast track of the flavour below as side by side video instead of generating it')
            ->end()
            ->scalarNode('flavour')
            ->defaultValue('composition/delivery')
            ->info('Flavour of the Opencast side by side track')
            ->end()
            ->end()
            ->end()
            ->scalarNode('default_tag_imported')
            ->defaultValue('TECHOPENCAST')
            ->info('Tag added to the imported multimedia objects')
            ->end()
            ->integerNode('seconds_to_sleep_on_commands')
            ->defaultValue(1)
            ->min(0)
            ->info('Seconds between the requests of the migration commands, for the firewalls that block bursts')
            ->end()
            ->arrayNode('notifications')
            ->addDefaultsIfNotSet()
            ->info('Email to the owners and groups when a recording is imported')
            ->children()
            ->booleanNode('enabled')->defaultFalse()->end()
            ->scalarNode('template')->defaultValue(self::DEFAULT_NOTIFICATION_TEMPLATE)->end()
            ->scalarNode('url')->defaultValue('pumukitnewadmin_mms_shortener')->info('Route name, or URL with {{id}}')->end()
            ->scalarNode('subject')->defaultValue('Your recording "{{multimediaObject.title}}" is now available')->end()
            ->end()
            ->end()
            ->end()
        ;

        return $treeBuilder;
    }
}
